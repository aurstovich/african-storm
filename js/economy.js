/* ================================================================
   ЭКОНОМИКА — очки, доход, покупка подкреплений
   Спавн: у спавнера игрока (и ИИ)
   ================================================================ */

import { НАСТРОЙКИ } from './config.js';
import { здания } from './world.js';
import { добавитьВзрыв, добавитьТекст } from './effects.js';
import { виднаТочка, разведанаТочка } from './fog.js';

let _юниты = null;
let _обновитьИнтерфейс = null;
let _создатьОтряд = null;

export const очки = {
    gurun: НАСТРОЙКИ.СТАРТОВЫЕ_ОЧКИ,
    burun: НАСТРОЙКИ.СТАРТОВЫЕ_ОЧКИ
};

let таймерДохода = 0;

const очередьСпавна = {
    gurun: {
        infantry: { осталось: 0, всего: 0, x: 0, y: 0 },
        sniper:   { осталось: 0, всего: 0, x: 0, y: 0 }
    },
    burun: {
        infantry: { осталось: 0, всего: 0, x: 0, y: 0 },
        sniper:   { осталось: 0, всего: 0, x: 0, y: 0 }
    }
};

export function подключитьЭкономику(юниты, обновитьИнтерфейс, создатьОтряд) {
    _юниты = юниты;
    _обновитьИнтерфейс = обновитьИнтерфейс;
    _создатьОтряд = создатьОтряд;
}

export function получитьОчки(команда = 'gurun') {
    return очки[команда] || 0;
}

export function потратитьОчки(команда, сколько) {
    if (очки[команда] !== undefined) очки[команда] -= сколько;
}

export function получитьСостояниеСпавна(команда, тип) {
    return очередьСпавна[команда]?.[тип] || null;
}

export function обновитьЭкономику(кадровПрошло) {
    таймерДохода += кадровПрошло;
    if (таймерДохода >= НАСТРОЙКИ.ИНТЕРВАЛ_ДОХОДА) {
        таймерДохода -= НАСТРОЙКИ.ИНТЕРВАЛ_ДОХОДА;
        const зданийГурун = здания.filter(з => з.владелец === 'gurun').length;
        const зданийБурун = здания.filter(з => з.владелец === 'burun').length;
        if (зданийГурун > 0) очки.gurun += зданийГурун;
        if (зданийБурун > 0) очки.burun += зданийБурун;
    }

    for (const команда of ['gurun', 'burun']) {
        for (const тип of ['infantry', 'sniper']) {
            const запись = очередьСпавна[команда][тип];
            if (запись.осталось > 0) {
                запись.осталось -= кадровПрошло;
                if (запись.осталось <= 0) {
                    запись.осталось = 0;
                    завершитьСпавн(команда, тип, запись);
                }
            }
        }
    }

    if (_обновитьИнтерфейс) _обновитьИнтерфейс();
}

function найтиСпавнер(команда) {
    return здания.find(з => з.тип === 'spawner' && з.владелец === команда);
}

function проверитьТочкуСпавна(x, y) {
    if (!разведанаТочка(x, y)) return false;
    const радиус = НАСТРОЙКИ.МИН_РАССТОЯНИЕ_ОТ_ВРАЖЕСКОГО_ЗДАНИЯ;
    for (const з of здания) {
        if (з.владелец !== 'burun') continue;
        const cx = з.x + з.ширина / 2;
        const cy = з.y + з.высота / 2;
        if (Math.hypot(cx - x, cy - y) < радиус) return false;
    }
    return true;
}

export function можноКупитьСейчас(тип) {
    const запись = очередьСпавна.gurun[тип];
    return запись && запись.осталось <= 0;
}

export function купитьПодкрепление(тип) {
    const конфиг = НАСТРОЙКИ.ЮНИТЫ[тип];
    if (!конфиг) return;

    const цена = конфиг.ЦЕНА;
    if (очки.gurun < цена) return;

    const запись = очередьСпавна.gurun[тип];
    if (запись.осталось > 0) return;

    const спавнер = найтиСпавнер('gurun');
    if (!спавнер) {
        добавитьТекст(200, 900 - 20, 'НЕТ СПАВНЕРА!', '#ff3030');
        return;
    }

    let spawnX = спавнер.x + спавнер.ширина / 2;
    let spawnY = спавнер.y + спавнер.высота / 2;
    
    const угол = Math.random() * Math.PI * 2;
    const r = Math.max(спавнер.ширина, спавнер.высота) / 2 + 30;
    spawnX += Math.cos(угол) * r;
    spawnY += Math.sin(угол) * r;

    spawnX = Math.max(20, Math.min(НАСТРОЙКИ.РАЗМЕР_МИРА - 20, spawnX));
    spawnY = Math.max(20, Math.min(НАСТРОЙКИ.РАЗМЕР_МИРА - 20, spawnY));

    очки.gurun -= цена;

    const времяСпавна = конфиг.ВРЕМЯ_СПАВНА;
    запись.осталось = времяСпавна;
    запись.всего = времяСпавна;
    запись.x = spawnX;
    запись.y = spawnY;

    добавитьТекст(spawnX, spawnY - 20, `⏳ ${Math.ceil(времяСпавна / 60)}с`, '#ffcc66');
    if (_обновитьИнтерфейс) _обновитьИнтерфейс();
}

// НОВАЯ ФУНКЦИЯ ДЛЯ ИИ
export function запуститьСпавнДляИИ(тип) {
    const конфиг = НАСТРОЙКИ.ЮНИТЫ[тип];
    if (!конфиг) return false;

    const цена = конфиг.ЦЕНА;
    if (очки.burun < цена) return false;

    const запись = очередьСпавна.burun[тип];
    if (запись.осталось > 0) return false;

    const спавнер = найтиСпавнер('burun');
    if (!спавнер) return false;

    let spawnX = спавнер.x + спавнер.ширина / 2;
    let spawnY = спавнер.y + спавнер.высота / 2;
    
    const угол = Math.random() * Math.PI * 2;
    const r = Math.max(спавнер.ширина, спавнер.высота) / 2 + 30;
    spawnX += Math.cos(угол) * r;
    spawnY += Math.sin(угол) * r;

    spawnX = Math.max(20, Math.min(НАСТРОЙКИ.РАЗМЕР_МИРА - 20, spawnX));
    spawnY = Math.max(20, Math.min(НАСТРОЙКИ.РАЗМЕР_МИРА - 20, spawnY));

    очки.burun -= цена;

    const времяСпавна = конфиг.ВРЕМЯ_СПАВНА;
    запись.осталось = времяСпавна;
    запись.всего = времяСпавна;
    запись.x = spawnX;
    запись.y = spawnY;
    
    return true;
}

function завершитьСпавн(команда, тип, запись) {
    if (команда === 'gurun' && !проверитьТочкуСпавна(запись.x, запись.y)) {
        const конфиг = НАСТРОЙКИ.ЮНИТЫ[тип];
        if (конфиг) очки[команда] += конфиг.ЦЕНА;
        добавитьТекст(запись.x, запись.y - 20, 'ОТМЕНЕНО (туман)', '#ff6060');
        return;
    }

    if (_создатьОтряд) _создатьОтряд(запись.x, запись.y, команда, тип);
    const цвет = команда === 'gurun' ? '#4a90d9' : '#d94a4a';
    добавитьВзрыв(запись.x, запись.y, цвет, 25);
    добавитьТекст(запись.x, запись.y - 20, '+ ПОДКРЕПЛЕНИЕ', цвет);
}