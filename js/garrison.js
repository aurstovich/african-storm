/* ================================================================
   ГАРНИЗОНЫ — вход/выход отрядов из зданий
   ================================================================ */

import { НАСТРОЙКИ } from './config.js';

// Ссылка на массив юнитов устанавливается из main.js
let _юниты = null;
let _обновитьИнтерфейс = null;

export function подключитьГарнизон(юниты, обновитьИнтерфейс) {
    _юниты = юниты;
    _обновитьИнтерфейс = обновитьИнтерфейс;
}

export function войтиВГарнизон(отряд, здание) {
    if (здание.гарнизон.length >= НАСТРОЙКИ.ВМЕСТИМОСТЬ_ЗДАНИЯ) return;
    if (здание.гарнизон.includes(отряд)) return;
    здание.гарнизон.push(отряд);
    отряд.вГарнизоне = здание;
    отряд.цель = null;
    отряд.цельАтаки = null;
    обновитьВладельцевЗданий();
    if (_обновитьИнтерфейс) _обновитьИнтерфейс();
}

export function выйтиИзГарнизона(отряд) {
    const з = отряд.вГарнизоне;
    if (!з) return;
    const угол = Math.random() * Math.PI * 2;
    отряд.x = з.x + з.ширина / 2 + Math.cos(угол) * (Math.max(з.ширина, з.высота) / 2 + 20);
    отряд.y = з.y + з.высота / 2 + Math.sin(угол) * (Math.max(з.ширина, з.высота) / 2 + 20);
    отряд.вГарнизоне = null;
    з.гарнизон = з.гарнизон.filter(о => о !== отряд);
    обновитьВладельцевЗданий();
    if (_обновитьИнтерфейс) _обновитьИнтерфейс();
}

export function обновитьВладельцевЗданий(здания) {
    const массив = здания || [];
    for (const з of массив) {
        const живые = з.гарнизон.filter(о => о.жив);
        з.гарнизон = живые;
        if (живые.length === 0) з.владелец = null;
        else з.владелец = живые[0].команда;
    }
}