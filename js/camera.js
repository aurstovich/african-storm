/* ================================================================
   КАМЕРА — положение, зум, преобразование координат
   ================================================================ */

import { НАСТРОЙКИ } from './config.js';

export const холст = document.getElementById('game');
export const контекст = холст.getContext('2d');

export let ШИРИНА_ЭКРАНА = window.innerWidth;
export let ВЫСОТА_ЭКРАНА = window.innerHeight;
холст.width = ШИРИНА_ЭКРАНА;
холст.height = ВЫСОТА_ЭКРАНА;

export const камера = { x: 0, y: 0, зум: 1 };

export function экранВМир(screenX, screenY) {
    return {
        x: screenX / камера.зум + камера.x,
        y: screenY / камера.зум + камера.y
    };
}

export function ограничитьКамеру() {
    const вШ = ШИРИНА_ЭКРАНА / камера.зум;
    const вВ = ВЫСОТА_ЭКРАНА / камера.зум;
    камера.x = Math.max(0, Math.min(камера.x, НАСТРОЙКИ.РАЗМЕР_МИРА - вШ));
    камера.y = Math.max(0, Math.min(камера.y, НАСТРОЙКИ.РАЗМЕР_МИРА - вВ));
    if (НАСТРОЙКИ.РАЗМЕР_МИРА < вШ) камера.x = (НАСТРОЙКИ.РАЗМЕР_МИРА - вШ) / 2;
    if (НАСТРОЙКИ.РАЗМЕР_МИРА < вВ) камера.y = (НАСТРОЙКИ.РАЗМЕР_МИРА - вВ) / 2;
}

export function обновитьРазмеры() {
    ШИРИНА_ЭКРАНА = window.innerWidth;
    ВЫСОТА_ЭКРАНА = window.innerHeight;
    холст.width = ШИРИНА_ЭКРАНА;
    холст.height = ВЫСОТА_ЭКРАНА;
    ограничитьКамеру();
}