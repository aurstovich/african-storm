/* ================================================================
   ИИ БУРУНДИИ v2 — умнее, с ролями, отступлением и ударной группой
   ================================================================ */

import { НАСТРОЙКИ } from './config.js';
import { здания } from './world.js';
import { линияОгняСвободна } from './lineOfSight.js';
import { получитьОчки, потратитьОчки } from './economy.js';

let _юниты = null;
let _создатьОтряд = null;
let _обновитьИнтерфейс = null;

export function подключитьИИ(юниты, создатьОтряд, обновитьИнтерфейс) {
    _юниты = юниты;
    _создатьОтряд = создатьОтряд;
    _обновитьИнтерфейс = обновитьИнтерфейс;
}

// ================================================================
// ПАРАМЕТРЫ ИИ
// ================================================================
const ИНТЕРВАЛ_РЕШЕНИЯ = 120;        // ~2 сек между решениями
const МАКСИМУМ_ОТРЯДОВ = 10;         // лимит армии ИИ
const РАДИУС_АТАКИ_ИИ = 350;         // радиус обнаружения врага
const РАЗМЕР_УДАРНОЙ_ГРУППЫ = 4;     // сколько отрядов копим для удара
const ПОРОГ_ОТСТУПЛЕНИЯ = 0.5;       // отступаем, если потеряно >50% бойцов
const ВРЕМЯ_ПАМЯТИ = 600;            // кадров (~10 сек), сколько помним врага
const МАКС_ПОПЫТОК_АТАКИ = 3;        // сколько раз отряд идёт в атаку, потом отступает

let таймерРешения = 0;

// Память ИИ: последняя замеченная позиция врага
const память = {
    позицияВрага: null,
    времяПамяти: 0
};

// Роли отрядов: Map<отряд, 'захват' | 'гарнизон' | 'ударная'>
const роли = new Map();

export function обновитьИИ(кадровПрошло) {
    if (!_юниты || !_создатьОтряд) return;

    // Обновляем память
    if (память.времяПамяти > 0) {
        память.времяПамяти -= кадровПрошло;
        if (память.времяПамяти <= 0) {
            память.позицияВрага = null;
        }
    }

    таймерРешения += кадровПрошло;
    if (таймерРешения < ИНТЕРВАЛ_РЕШЕНИЯ) return;
    таймерРешения = 0;

    принятьРешение();
}

// ================================================================
// СТРАТЕГИЧЕСКОЕ РЕШЕНИЕ (раз в 2 сек)
// ================================================================
function принятьРешение() {
    const мои = _юниты.filter(ю => ю.жив && ю.команда === 'burun');
    const враги = _юниты.filter(ю => ю.жив && ю.команда === 'gurun');
    const моиЗдания = здания.filter(з => з.владелец === 'burun');
    const вражескиеЗдания = здания.filter(з => з.владелец === 'gurun');
    const нейтральные = здания.filter(з => !з.владелец);

    // Запоминаем позицию врага, если видим
    запомнитьВрага(мои, враги);

    // Назначаем роли отрядам, у которых их нет
    назначитьРоли(мои, нейтральные, моиЗдания);

    // Отступление — в первую очередь
    отступать(мои, моиЗдания);

    // Атака — если враг близко
    if (мои.length > 0 && враги.length > 0) {
        атаковатьБлижайших(мои, враги);
    }

    // Захват нейтральных зданий
    if (нейтральные.length > 0) {
        захватыватьЗдания(мои, нейтральные);
    }

    // Захват вражеских зданий — если есть преимущество
    if (вражескиеЗдания.length > 0 && естьПреимущество(мои, враги)) {
        захватыватьЗдания(мои, вражескиеЗдания);
    }

    // Гарнизон — снайперы в здания
    оборонятьЗдания(мои, моиЗдания);

    // Ударная группа — если накопили достаточно
    if (мои.length >= РАЗМЕР_УДАРНОЙ_ГРУППЫ && моиЗдания.length >= 2) {
        ударнаяГруппа(мои, враги, вражескиеЗдания);
    }

    // Покупка
    if (мои.length < МАКСИМУМ_ОТРЯДОВ) {
        покупать(мои, моиЗдания, враги);
    }

    if (_обновитьИнтерфейс) _обновитьИнтерфейс();
}

// ================================================================
// ПАМЯТЬ
// ================================================================
function запомнитьВрага(мои, враги) {
    for (const отряд of мои) {
        const поз = отряд.позиция;
        for (const враг of враги) {
            if (!враг.жив) continue;
            const вп = враг.позиция;
            if (Math.hypot(вп.x - поз.x, вп.y - поз.y) < отряд.обнаружение) {
                память.позицияВрага = { x: вп.x, y: вп.y };
                память.времяПамяти = ВРЕМЯ_ПАМЯТИ;
                return;
            }
        }
    }
}

// ================================================================
// РОЛИ
// ================================================================
function назначитьРоли(мои, нейтральные, моиЗдания) {
    // Чистим роли мёртвых
    for (const [отряд] of роли) {
        if (!отряд.жив) роли.delete(отряд);
    }

    // Снайперы — гарнизон
    for (const отряд of мои) {
        if (отряд.тип === 'sniper' && !роли.has(отряд)) {
            роли.set(отряд, 'гарнизон');
        }
    }

    // Пехота — захват или ударная
    const пехота = мои.filter(о => о.тип === 'infantry' && !роли.has(о));
    for (let i = 0; i < пехота.length; i++) {
        // Первые 2 пехотинца — захват (расширение), остальные — ударная группа
        if (нейтральные.length > 0 && i < 2) {
            роли.set(пехота[i], 'захват');
        } else {
            роли.set(пехота[i], 'ударная');
        }
    }
}

// ================================================================
// ОТСТУПЛЕНИЕ
// ================================================================
function отступать(мои, моиЗдания) {
    for (const отряд of мои) {
        if (отряд.вГарнизоне) continue;
        if (!отряд.жив) continue;

        const процент = отряд.здоровье / отряд.максЗдоровье;
        if (процент > ПОРОГ_ОТСТУПЛЕНИЯ) continue;

        // Ищем ближайшее своё здание
        if (моиЗдания.length === 0) continue;

        let ближайшее = null, лучшаяД = Infinity;
        const поз = отряд.позиция;
        for (const з of моиЗдания) {
            if (з.гарнизон.length >= НАСТРОЙКИ.ВМЕСТИМОСТЬ_ЗДАНИЯ) continue;
            const cx = з.x + з.ширина / 2;
            const cy = з.y + з.высота / 2;
            const d = Math.hypot(cx - поз.x, cy - поз.y);
            if (d < лучшаяД) { лучшаяД = d; ближайшее = з; }
        }

        if (ближайшее && !отряд.приказВойтиВ) {
            отряд.приказВойтиВ = ближайшее;
            отряд.цель = null;
            отряд.цельАтаки = null;
        }
    }
}

// ================================================================
// АТАКА
// ================================================================
function атаковатьБлижайших(мои, враги) {
    for (const отряд of мои) {
        if (отряд.вГарнизоне) continue;
        if (отряд.цельАтаки && отряд.цельАтаки.жив) continue;
        if (отряд.приказВойтиВ) continue;

        let ближайший = null;
        let лучшаяД = Infinity;
        const поз = отряд.позиция;

        for (const враг of враги) {
            if (!враг.жив) continue;
            const вп = враг.позиция;
            const d = Math.hypot(вп.x - поз.x, вп.y - поз.y);
            if (d < лучшаяД && d <= РАДИУС_АТАКИ_ИИ) {
                if (линияОгняСвободна(поз.x, поз.y, вп.x, вп.y, отряд, враг)) {
                    лучшаяД = d;
                    ближайший = враг;
                }
            }
        }

        if (ближайший) {
            отряд.цельАтаки = ближайший;
            отряд.цель = null;
        }
    }
}

// ================================================================
// ЗАХВАТ
// ================================================================
function захватыватьЗдания(мои, целевыеЗдания) {
    const занятыеЦели = new Set();
    for (const отряд of мои) {
        if (отряд.приказВойтиВ) занятыеЦели.add(отряд.приказВойтиВ);
    }

    // Только отряды с ролью «захват» или без роли
    const свободные = мои.filter(о => {
        if (о.вГарнизоне) return false;
        if (о.приказВойтиВ) return false;
        if (о.цельАтаки && о.цельАтаки.жив) return false;
        const роль = роли.get(о);
        return роль === 'захват' || роль === undefined;
    });

    const свободныеЗдания = целевыеЗдания.filter(з =>
        !занятыеЦели.has(з) &&
        з.гарнизон.length < НАСТРОЙКИ.ВМЕСТИМОСТЬ_ЗДАНИЯ
    );

    if (свободные.length === 0 || свободныеЗдания.length === 0) return;

    for (const отряд of свободные) {
        if (свободныеЗдания.length === 0) break;

        let ближайшее = null;
        let лучшаяД = Infinity;
        const поз = отряд.позиция;

        for (const з of свободныеЗдания) {
            const cx = з.x + з.ширина / 2;
            const cy = з.y + з.высота / 2;
            const d = Math.hypot(cx - поз.x, cy - поз.y);
            if (d < лучшаяД) {
                лучшаяД = d;
                ближайшее = з;
            }
        }

        if (ближайшее) {
            отряд.приказВойтиВ = ближайшее;
            отряд.цель = null;
            отряд.цельАтаки = null;
            const индекс = свободныеЗдания.indexOf(ближайшее);
            if (индекс >= 0) свободныеЗдания.splice(индекс, 1);
        }
    }
}

// ================================================================
// ОБОРОНА (гарнизон)
// ================================================================
function оборонятьЗдания(мои, моиЗдания) {
    const снайперы = мои.filter(о =>
        о.тип === 'sniper' && !о.вГарнизоне && !о.приказВойтиВ
    );

    if (снайперы.length === 0 || моиЗдания.length === 0) return;

    const свободные = моиЗдания.filter(з => з.гарнизон.length < НАСТРОЙКИ.ВМЕСТИМОСТЬ_ЗДАНИЯ);
    if (свободные.length === 0) return;

    for (const снайпер of снайперы) {
        if (свободные.length === 0) break;
        let ближайшее = null, лучшаяД = Infinity;
        const поз = снайпер.позиция;
        for (const з of свободные) {
            const cx = з.x + з.ширина / 2;
            const cy = з.y + з.высота / 2;
            const d = Math.hypot(cx - поз.x, cy - поз.y);
            if (d < лучшаяД) { лучшаяД = d; ближайшее = з; }
        }
        if (ближайшее) {
            снайпер.приказВойтиВ = ближайшее;
            снайпер.цель = null;
            снайпер.цельАтаки = null;
            const индекс = свободные.indexOf(ближайшее);
            if (индекс >= 0) свободные.splice(индекс, 1);
        }
    }
}

// ================================================================
// УДАРНАЯ ГРУППА
// ================================================================
function ударнаяГруппа(мои, враги, вражескиеЗдания) {
    // Собираем отряды с ролью «ударная»
    const ударники = мои.filter(о =>
        роли.get(о) === 'ударная' && !о.вГарнизоне
    );

    if (ударники.length < РАЗМЕР_УДАРНОЙ_ГРУППЫ) return;

    // Ищем цель:
    // 1. Администрация в центре (главная цель)
    // 2. Скопление врагов (если есть)
    // 3. Ближайшее вражеское здание
    let цель = null;
    let цельТип = null;

    const админ = вражескиеЗдания.find(з => з.тип === 'admin');
    if (админ) {
        цель = { x: админ.x + админ.ширина / 2, y: админ.y + админ.высота / 2 };
        цельТип = 'admin';
    }

    if (!цель && память.позицияВрага) {
        цель = { ...память.позицияВрага };
        цельТип = 'память';
    }

    if (!цель && вражескиеЗдания.length > 0) {
        const з = вражескиеЗдания[0];
        цель = { x: з.x + з.ширина / 2, y: з.y + з.высота / 2 };
        цельТип = 'building';
    }

    if (!цель) return;

    // Ведём всю группу к цели
    for (const отряд of ударники) {
        if (отряд.приказВойтиВ) continue;
        // Если уже есть цель атаки — не трогаем
        if (отряд.цельАтаки && отряд.цельАтаки.жив) continue;

        отряд.цель = { x: цель.x, y: цель.y };
        отряд.цельАтаки = null;
    }
}

// ================================================================
// ПРЕИМУЩЕСТВО
// ================================================================
function естьПреимущество(мои, враги) {
    // Считаем «силу»: сумма здоровья всех отрядов
    const мояСила = мои.reduce((с, о) => с + о.здоровье, 0);
    const силаВрага = враги.reduce((с, о) => с + о.здоровье, 0);
    return мояСила > силаВрага * 1.3;
}

// ================================================================
// ПОКУПКА
// ================================================================
function покупать(мои, моиЗдания, враги) {
    const текущиеОчки = получитьОчки('burun');
    if (текущиеОчки < НАСТРОЙКИ.ЦЕНА_ПЕХОТЫ) return;

    // Адаптивная стратегия
    const соотношение = мои.length / Math.max(1, враги.length);
    let тип = 'infantry';
    let цена = НАСТРОЙКИ.ЦЕНА_ПЕХОТЫ;

    // Если у ИИ мало зданий — покупаем пехоту (захват)
    // Если зданий много и есть преимущество — покупаем снайперов (оборона + удар)
    if (моиЗдания.length >= 2 && соотношение >= 1) {
        if (текущиеОчки >= НАСТРОЙКИ.ЦЕНА_СНАЙПЕРОВ && Math.random() < 0.4) {
            тип = 'sniper';
            цена = НАСТРОЙКИ.ЦЕНА_СНАЙПЕРОВ;
        }
    }

    if (текущиеОчки < цена) return;

    // Точка спавна
    let spawnX = 1800, spawnY = 400;
    if (моиЗдания.length > 0) {
        const з = моиЗдания[Math.floor(Math.random() * моиЗдания.length)];
        const угол = Math.random() * Math.PI * 2;
        const r = Math.max(з.ширина, з.высота) / 2 + 30;
        spawnX = з.x + з.ширина / 2 + Math.cos(угол) * r;
        spawnY = з.y + з.высота / 2 + Math.sin(угол) * r;
    } else {
        const первый = _юниты.find(ю => ю.жив && ю.команда === 'burun');
        if (первый) { spawnX = первый.x + 30; spawnY = первый.y + 30; }
    }

    spawnX = Math.max(20, Math.min(НАСТРОЙКИ.РАЗМЕР_МИРА - 20, spawnX));
    spawnY = Math.max(20, Math.min(НАСТРОЙКИ.РАЗМЕР_МИРА - 20, spawnY));

    потратитьОчки('burun', цена);
    _создатьОтряд(spawnX, spawnY, 'burun', тип);
}