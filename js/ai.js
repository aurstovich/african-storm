import { виднаТочка, туманВключен } from './fog.js';

let _юниты = null;
let _создатьОтряд = null;
let _обновитьИнтерфейс = null;

export function подключитьИИ(юниты, создатьОтряд, обновитьИнтерфейс) {
    _юниты = юниты;
    _создатьОтряд = создатьОтряд;
    _обновитьИнтерфейс = обновитьИнтерфейс;
}

// ================================================================
// ПАРАМЕТРЫ
// ================================================================
const ИНТЕРВАЛ_РЕШЕНИЯ = 90;
const РАЗМЕР_УДАРНОЙ_ГРУППЫ = 3;
const ПОРОГ_ОТСТУПЛЕНИЯ = 0.3;
const ВРЕМЯ_ПАМЯТИ = 900;

// Максимальное расстояние, на котором ИИ "видит" врага (даже если туман выключен)
const РАДИУС_ОБЗОРА_ИИ = 400;

let таймерРешения = 0;
const память = { позицияВрага: null, времяПамяти: 0 };
const роли = new Map();

export function обновитьИИ(кадровПрошло) {
    if (!_юниты || !_создатьОтряд) return;

    if (память.времяПамяти > 0) {
        память.времяПамяти -= кадровПрошло;
        if (память.времяПамяти <= 0) память.позицияВрага = null;
    }

    таймерРешения += кадровПрошло;
    if (таймерРешения < ИНТЕРВАЛ_РЕШЕНИЯ) return;
    таймерРешения = 0;

    принятьРешение();
}

function принятьРешение() {
    const мои = _юниты.filter(ю => ю.жив && ю.команда === 'burun');
    const враги = _юниты.filter(ю => ю.жив && ю.команда === 'gurun');
    const моиЗдания = здания.filter(з => з.владелец === 'burun');
    const вражескиеЗдания = здания.filter(з => з.владелец === 'gurun');
    const нейтральные = здания.filter(з => !з.владелец);

    запомнитьВрага(мои, враги);
    назначитьРоли(мои, нейтральные, моиЗдания);
    
    отступать(мои, моиЗдания);

    // Атакуем только тех, до кого реально можем дотянуться
    if (мои.length > 0 && враги.length > 0) {
        атаковатьБлижайших(мои, враги);
    }

    if (нейтральные.length > 0) {
        захватыватьЗдания(мои, нейтральные, враги);
    }

    if (вражескиеЗдания.length > 0) {
        захватыватьЗдания(мои, вражескиеЗдания, враги);
    }

    оборонятьЗдания(мои, моиЗдания);
    
    if (мои.length >= РАЗМЕР_УДАРНОЙ_ГРУППЫ) {
        ударнаяГруппа(мои, враги, вражескиеЗдания);
    }

    покупать(мои, моиЗдания, враги);

    if (_обновитьИнтерфейс) _обновитьИнтерфейс();
}

// ================================================================
// ВСПОМОГАТЕЛЬНЫЕ
// ================================================================
function запомнитьВрага(мои, враги) {
    for (const отряд of мои) {
        const поз = отряд.позиция;
        for (const враг of враги) {
            if (!враг.жив) continue;
            const вп = враг.позиция;
            if (Math.hypot(вп.x - поз.x, вп.y - поз.y) < отряд.обнаружение && виднаТочка(вп.x, вп.y)) {
                память.позицияВрага = { x: вп.x, y: вп.y };
                память.времяПамяти = ВРЕМЯ_ПАМЯТИ;
                return;
            }
        }
    }
}

function назначитьРоли(мои, нейтральные, моиЗдания) {
    for (const [отряд] of роли) { if (!отряд.жив) роли.delete(отряд); }
    for (const отряд of мои) {
        if (отряд.тип === 'sniper' && !роли.has(отряд)) роли.set(отряд, 'гарнизон');
    }
    
    const пехота = мои.filter(о => о.тип === 'infantry' && !роли.has(о));
    for (let i = 0; i < пехота.length; i++) {
        if (нейтральные.length > 0) роли.set(пехота[i], 'захват');
        else роли.set(пехота[i], 'ударная');
    }
}

function оценитьОпасность(x, y, враги) {
    let опасность = 0;
    for (const враг of враги) {
        if (!враг.жив) continue;
        const вп = враг.позиция;
        const d = Math.hypot(вп.x - x, вп.y - y);
        if (d < враг.дальность && виднаТочка(вп.x, вп.y)) {
            if (враг.тип === 'sniper') опасность += 3;
            else опасность += 1;
        }
    }
    return опасность;
}

