import { НАСТРОЙКИ } from './config.js';
import { здания } from './world.js';
import { линияОгняСвободна } from './lineOfSight.js';
import { получитьОчки, запуститьСпавнДляИИ, получитьСостояниеСпавна } from './economy.js';
import { виднаТочка } from './fog.js';

let _юниты = null;
let _создатьОтряд = null;
let _обновитьИнтерфейс = null;

export function подключитьИИ(юниты, создатьОтряд, обновитьИнтерфейс) {
    _юниты = юниты;
    _создатьОтряд = создатьОтряд;
    _обновитьИнтерфейс = обновитьИнтерфейс;
}

const ИНТЕРВАЛ_РЕШЕНИЯ = 120;        
const РАДИУС_ОБЗОРА_ИИ = 500;         
const РАЗМЕР_УДАРНОЙ_ГРУППЫ = 5;     
const ПОРОГ_ОТСТУПЛЕНИЯ = 0.4;       

let таймерРешения = 0;
let режим = 'накопление';
let силаАрмииНаПрошломШаге = 0;
let потериЗаШаг = 0;

const память = { позицияВрага: null, времяПамяти: 0 };
const роли = new Map();

export function обновитьИИ(кадровПрошло) {
    if (!_юниты || !_создатьОтряд) return;

    if (память.времяПамяти > 0) {
        память.времяПамяти -= кадровПрошло;
        if (память.времяПамяти <= 0) память.позицияВрага = null;
    }

    таймерРешения += кадровПрошло;
    if (таймерРешения < ИНТЕРВАЛ_РЕШЕНИЯ) return;
    таймерРешения = 0;

    принятьРешение();
}

function принятьРешение() {
    const мои = _юниты.filter(ю => ю.жив && ю.команда === 'burun');
    const враги = _юниты.filter(ю => ю.жив && ю.команда === 'gurun');
    const моиЗдания = здания.filter(з => з.владелец === 'burun');
    const вражескиеЗдания = здания.filter(з => з.владелец === 'gurun');
    const нейтральные = здания.filter(з => !з.владелец);

    const текущаяСила = мои.reduce((с, о) => с + о.здоровье, 0);
    const силаВрага = враги.reduce((с, о) => с + о.здоровье, 0);

    потериЗаШаг = Math.max(0, силаАрмииНаПрошломШаге - текущаяСила);
    силаАрмииНаПрошломШаге = текущаяСила;

    const процентПотерь = потериЗаШаг / Math.max(1, текущаяСила);

    if (процентПотерь > 0.3 && режим === 'наступление') {
        режим = 'отступление';
    } else if (режим === 'отступление' && текущаяСила > силаАрмииНаПрошломШаге * 1.2) {
        режим = 'накопление';
    } else if (режим === 'накопление' && мои.length >= РАЗМЕР_УДАРНОЙ_ГРУППЫ) {
        if (текущаяСила > силаВрага * 1.2 || мои.length >= РАЗМЕР_УДАРНОЙ_ГРУППЫ + 2) {
            режим = 'наступление';
        }
    }

    запомнитьВрага(мои, враги);
    назначитьРоли(мои, нейтральные, моиЗдания);

    if (режим === 'наступление') {
        атаковатьБлижайших(мои, враги);
        ударнаяГруппа(мои, враги, вражескиеЗдания);
    } else if (режим === 'отступление') {
        отступать(мои, моиЗдания);
        оборонятьЗдания(мои, моиЗдания);
        for (const отряд of мои) {
            if (!отряд.вГарнизоне && !отряд.приказВойтиВ && моиЗдания.length > 0) {
                let ближайшее = null, лучшаяД = Infinity;
                const поз = отряд.позиция;
                for (const з of моиЗдания) {
                    if (з.гарнизон.length >= НАСТРОЙКИ.ВМЕСТИМОСТЬ_ЗДАНИЯ) continue;
                    const cx = з.x + з.ширина / 2;
                    const cy = з.y + з.высота / 2;
                    const d = Math.hypot(cx - поз.x, cy - поз.y);
                    if (d < лучшаяД) { лучшаяД = d; ближайшее = з; }
                }
                if (ближайшее) отряд.приказВойтиВ = ближайшее;
            }
        }
    } else {
        if (нейтральные.length > 0) захватыватьЗдания(мои, нейтральные, враги);
        оборонятьЗдания(мои, моиЗдания);
    }

    подобратьНовобранцев(мои, враги, моиЗдания, нейтральные, вражескиеЗдания);

    покупать(мои, моиЗдания, враги);

    if (_обновитьИнтерфейс) _обновитьИнтерфейс();
}

function подобратьНовобранцев(мои, враги, моиЗдания, нейтральные, вражескиеЗдания) {
    const бездельники = мои.filter(о => !о.вГарнизоне && !о.приказВойтиВ && (!о.цельАтаки || !о.цельАтаки.жив) && !о.цель);
    for (const отряд of бездельники) {
        if (нейтральные.length > 0) {
            let ближайшее = null, лучшаяД = Infinity;
            const поз = отряд.позиция;
            for (const з of нейтральные) {
                if (з.гарнизон.length >= НАСТРОЙКИ.ВМЕСТИМОСТЬ_ЗДАНИЯ) continue;
                const cx = з.x + з.ширина / 2;
                const cy = з.y + з.высота / 2;
                const d = Math.hypot(cx - поз.x, cy - поз.y);
                if (d < лучшаяД) { лучшаяД = d; ближайшее = з; }
            }
            if (ближайшее) {
                отряд.приказВойтиВ = ближайшее;
                отряд.цель = null;
                отряд.цельАтаки = null;
                continue;
            }
        }
        if (враги.length > 0) {
            let ближайший = null, лучшаяД = Infinity;
            const поз = отряд.позиция;
            for (const враг of враги) {
                if (!враг.жив) continue;
                const вп = враг.позиция;
                const d = Math.hypot(вп.x - поз.x, вп.y - поз.y);
                if (d < лучшаяД && виднаТочка(вп.x, вп.y)) {
                    лучшаяД = d;
                    ближайший = враг;
                }
            }
            if (ближайший) {
                отряд.цельАтаки = ближайший;
                отряд.цель = null;
                continue;
            }
        }
        if (вражескиеЗдания.length > 0) {
            const админ = вражескиеЗдания.find(з => з.тип === 'admin');
            if (админ) {
                отряд.цель = { x: админ.x + админ.ширина / 2, y: админ.y + админ.высота / 2 };
            }
        }
    }
}

function запомнитьВрага(мои, враги) {
    for (const отряд of мои) {
        const поз = отряд.позиция;
        for (const враг of враги) {
            if (!враг.жив) continue;
            const вп = враг.позиция;
            if (Math.hypot(вп.x - поз.x, вп.y - поз.y) < отряд.обнаружение && виднаТочка(вп.x, вп.y)) {
                память.позицияВрага = { x: вп.x, y: вп.y };
                память.времяПамяти = 600;
                return;
            }
        }
    }
}

function назначитьРоли(мои, нейтральные, моиЗдания) {
    for (const [отряд] of роли) { if (!отряд.жив) роли.delete(отряд); }
    for (const отряд of мои) {
        if (отряд.тип === 'sniper' && !роли.has(отряд)) роли.set(отряд, 'гарнизон');
        else if (отряд.тип === 'tank' && !роли.has(отряд)) роли.set(отряд, 'ударная');
    }
    const пехота = мои.filter(о => о.тип === 'infantry' && !роли.has(о));
    for (let i = 0; i < пехота.length; i++) {
        if (режим === 'наступление') роли.set(пехота[i], 'ударная');
        else if (нейтральные.length > 0) роли.set(пехота[i], 'захват');
        else роли.set(пехота[i], 'ударная');
    }
}

function отступать(мои, моиЗдания) {
    for (const отряд of мои) {
        if (отряд.вГарнизоне || !отряд.жив) continue;
        if (отряд.приказВойтиВ) continue;
        const процент = отряд.здоровье / отряд.максЗдоровье;
        if (процент <= ПОРОГ_ОТСТУПЛЕНИЯ) {
            if (моиЗдания.length === 0) continue;
            let ближайшее = null, лучшаяД = Infinity;
            const поз = отряд.позиция;
            for (const з of моиЗдания) {
                if (з.гарнизон.length >= НАСТРОЙКИ.ВМЕСТИМОСТЬ_ЗДАНИЯ) continue;
                const cx = з.x + з.ширина / 2;
                const cy = з.y + з.высота / 2;
                const d = Math.hypot(cx - поз.x, cy - поз.y);
                if (d < лучшаяД) { лучшаяД = d; ближайшее = з; }
            }
            if (ближайшее) {
                отряд.приказВойтиВ = ближайшее;
                отряд.цель = null;
                отряд.цельАтаки = null;
            }
        }
    }
}

function атаковатьБлижайших(мои, враги) {
    for (const отряд of мои) {
        if (отряд.вГарнизоне || (отряд.цельАтаки && отряд.цельАтаки.жив) || отряд.приказВойтиВ) continue;
        let ближайший = null;
        let лучшаяД = Infinity;
        const поз = отряд.позиция;
        for (const враг of враги) {
            if (!враг.жив || враг.вГарнизоне) continue;
            const вп = враг.позиция;
            const d = Math.hypot(вп.x - поз.x, вп.y - поз.y);
            if (d < лучшаяД && d <= РАДИУС_ОБЗОРА_ИИ && виднаТочка(вп.x, вп.y)) {
                if (линияОгняСвободна(поз.x, поз.y, вп.x, вп.y, отряд, враг)) {
                    лучшаяД = d;
                    ближайший = враг;
                }
            }
        }
        if (ближайший) {
            отряд.цельАтаки = ближайший;
            отряд.цель = null;
        }
    }
}

function захватыватьЗдания(мои, целевыеЗдания, враги) {
    const занятыеЦели = new Set();
    for (const отряд of мои) { if (отряд.приказВойтиВ) занятыеЦели.add(отряд.приказВойтиВ); }
    const свободные = мои.filter(о => {
        if (о.вГарнизоне || о.приказВойтиВ || (о.цельАтаки && о.цельАтаки.жив)) return false;
        // Танк не может захватывать
        if (о.техника) return false;
        const роль = роли.get(о);
        return роль === 'захват' || роль === undefined;
    });
    const свободныеЗдания = целевыеЗдания.filter(з => !занятыеЦели.has(з) && з.гарнизон.length < НАСТРОЙКИ.ВМЕСТИМОСТЬ_ЗДАНИЯ);
    if (свободные.length === 0 || свободныеЗдания.length === 0) return;
    for (const отряд of свободные) {
        if (свободныеЗдания.length === 0) break;
        let ближайшее = null;
        let лучшаяД = Infinity;
        const поз = отряд.позиция;
        for (const з of свободныеЗдания) {
            const cx = з.x + з.ширина / 2;
            const cy = з.y + з.высота / 2;
            const d = Math.hypot(cx - поз.x, cy - поз.y);
            if (d < лучшаяД) { лучшаяД = d; ближайшее = з; }
        }
        if (ближайшее) {
            отряд.приказВойтиВ = ближайшее;
            отряд.цель = null;
            отряд.цельАтаки = null;
            const индекс = свободныеЗдания.indexOf(ближайшее);
            if (индекс >= 0) свободныеЗдания.splice(индекс, 1);
        }
    }
}

function оборонятьЗдания(мои, моиЗдания) {
    const снайперы = мои.filter(о => о.тип === 'sniper' && !о.вГарнизоне && !о.приказВойтиВ);
    if (снайперы.length === 0 || моиЗдания.length === 0) return;
    const свободные = моиЗдания.filter(з => з.гарнизон.length < НАСТРОЙКИ.ВМЕСТИМОСТЬ_ЗДАНИЯ);
    if (свободные.length === 0) return;
    for (const снайпер of снайперы) {
        if (свободные.length === 0) break;
        let ближайшее = null, лучшаяД = Infinity;
        const поз = снайпер.позиция;
        for (const з of свободные) {
            const cx = з.x + з.ширина / 2;
            const cy = з.y + з.высота / 2;
            const d = Math.hypot(cx - поз.x, cy - поз.y);
            if (d < лучшаяД) { лучшаяД = d; ближайшее = з; }
        }
        if (ближайшее) {
            снайпер.приказВойтиВ = ближайшее;
            снайпер.цель = null;
            снайпер.цельАтаки = null;
            const индекс = свободные.indexOf(ближайшее);
            if (индекс >= 0) свободные.splice(индекс, 1);
        }
    }
}

function ударнаяГруппа(мои, враги, вражескиеЗдания) {
    const ударники = мои.filter(о => роли.get(о) === 'ударная' && !о.вГарнизоне);
    if (ударники.length < РАЗМЕР_УДАРНОЙ_ГРУППЫ) return;
    let цель = null;
    if (память.позицияВрага) цель = { ...память.позицияВрага };
    else if (вражескиеЗдания.length > 0) {
        const админ = вражескиеЗдания.find(з => з.тип === 'admin');
        if (админ) цель = { x: админ.x + админ.ширина / 2, y: админ.y + админ.высота / 2 };
        else {
            const з = вражескиеЗдания[0];
            цель = { x: з.x + з.ширина / 2, y: з.y + з.высота / 2 };
        }
    }
    if (!цель) return;
    for (const отряд of ударники) {
        if (отряд.приказВойтиВ || (отряд.цельАтаки && отряд.цельАтаки.жив)) continue;
        отряд.цель = { x: цель.x, y: цель.y };
        отряд.цельАтаки = null;
    }
}

function покупать(мои, моиЗдания, враги) {
    const текущиеОчки = получитьОчки('burun');
    const состПех = получитьСостояниеСпавна('burun', 'infantry');
    const состСнп = получитьСостояниеСпавна('burun', 'sniper');
    const состТанк = получитьСостояниеСпавна('burun', 'tank');

    // Приоритет: Танк (если достаточно очков и нет в очереди)
    if (состТанк && состТанк.осталось === 0 && текущиеОчки >= НАСТРОЙКИ.ЮНИТЫ['tank'].ЦЕНА) {
        if (режим === 'наступление' || Math.random() < 0.2) {
            if (запуститьСпавнДляИИ('tank')) return;
        }
    }

    // Пехота
    if (состПех && состПех.осталось === 0 && текущиеОчки >= НАСТРОЙКИ.ЮНИТЫ['infantry'].ЦЕНА) {
        if (режим === 'наступление' || Math.random() < 0.7) {
            if (запуститьСпавнДляИИ('infantry')) return;
        }
    }

    // Снайперы
    if (состСнп && состСнп.осталось === 0 && текущиеОчки >= НАСТРОЙКИ.ЮНИТЫ['sniper'].ЦЕНА) {
        if (режим === 'наступление' || Math.random() < 0.4) {
            if (запуститьСпавнДляИИ('sniper')) return;
        }
    }
}