let последнееВремя = performance.now();
let таймерАвтосохранения = 0;

function обновитьИгру(сейчас) {
    const кадровПрошло = Math.min(3, (сейчас - последнееВремя) / (1000 / 60));
    последнееВремя = сейчас;

    if (состояние === 'playing' && играИнициализирована) {
        установитьКадровПрошло(кадровПрошло);

        const скор = НАСТРОЙКИ.СКОРОСТЬ_КАМЕРЫ / камера.зум;
        if (нажатыеКлавиши['w'] || нажатыеКлавиши['arrowup'])    камера.y -= скор;
        if (нажатыеКлавиши['s'] || нажатыеКлавиши['arrowdown'])  камера.y += скор;
        if (нажатыеКлавиши['a'] || нажатыеКлавиши['arrowleft'])  камера.x -= скор;
        if (нажатыеКлавиши['d'] || нажатыеКлавиши['arrowright']) камера.x += скор;
        ограничитьКамеру();

        for (const ю of юниты) ю.обновить(юниты, кадровПрошло);
        обновитьИИ(кадровПрошло);
        обновитьВладельцевЗданий(здания);
        обновитьТуман(юниты);
        обновитьЭкономику(кадровПрошло);

        // Обновление жизни обломков танков
        for (let i = обломкиТанков.length - 1; i >= 0; i--) {
            обломкиТанков[i].жизнь -= кадровПрошло;
            // Если жизнь закончилась, оставляем обломок (он просто дымится)
            if (обломкиТанков[i].жизнь < 0) обломкиТанков[i].жизнь = 0;
        }

        for (let i = эффекты.length - 1; i >= 0; i--) {
            const эф = эффекты[i];
            if (эф.тип === 'граната_таймер') {
                эф.жизнь -= кадровПрошло;
                if (эф.жизнь <= 0) {
                    эф.отряд.взорватьГранату(эф.x, эф.y, эф.всеЮниты);
                    эффекты.splice(i, 1);
                }
                continue;
            }
            эф.жизнь -= кадровПрошло;
            if (эф.жизнь <= 0) эффекты.splice(i, 1);
        }

        таймерАвтосохранения += кадровПрошло;
        if (таймерАвтосохранения >= 30 * 60) {
            таймерАвтосохранения = 0;
            сохранитьИгру();
        }

        проверитьКонецИгры();
    }

    requestAnimationFrame(обновитьИгру);
}

function циклОтрисовки() {
    if (играИнициализирована) {
        нарисовать();
        if (состояние === 'playing' || состояние === 'paused') {
            нарисоватьМиниКарту(document.getElementById('game').getContext('2d'));
        }
    } else {
        const ctx = document.getElementById('game').getContext('2d');
        ctx.fillStyle = '#0e0e0e';
        ctx.fillRect(0, 0, window.innerWidth, window.innerHeight);
    }
    requestAnimationFrame(циклОтрисовки);
}

function проверитьКонецИгры() {
    if (играОкончена) return;
    const живыГ = юниты.some(ю => ю.жив && ю.команда === 'gurun');
    const живыБ = юниты.some(ю => ю.жив && ю.команда === 'burun');
    const зданияГ = здания.some(з => з.владелец === 'gurun');
    const зданияБ = здания.some(з => з.владелец === 'burun');
    if (!живыГ && !зданияГ) завершитьИгру(false);
    else if (!живыБ && !зданияБ) завершитьИгру(true);
}

