const $ = (id) => document.getElementById(id);

function показатьЭкран(id) {
    ['main-menu', 'settings-menu', 'pause-menu', 'end-screen'].forEach(э => {
        $(э).classList.add('hidden');
    });
    if (id) $(id).classList.remove('hidden');
}

function обновитьВидимостьHUD() {
    const показывать = состояние === 'playing' || состояние === 'paused';
    $('right-panel').style.display = показывать ? '' : 'none';
    $('controls-hint').style.display = показывать ? '' : 'none';
    $('pause-btn').style.display = показывать ? '' : 'none';
    $('hud-toggle-open').style.display = 'none';
}

function обновитьКнопкуПродолжить() {
    const кнопка = $('btn-continue');
    const инфо = $('save-info');
    if (естьСохранение()) {
        кнопка.style.display = '';
        const время = времяСохранения();
        if (время) {
            const дата = new Date(время);
            const строка = дата.toLocaleString('ru-RU', {
                day: '2-digit', month: '2-digit',
                hour: '2-digit', minute: '2-digit'
            });
            инфо.textContent = `Сохранение: ${строка}`;
            инфо.style.display = '';
        }
    } else {
        кнопка.style.display = 'none';
        инфо.style.display = 'none';
    }
}

function перейтиВГлавноеМеню() {
    if ((состояние === 'paused' || состояние === 'playing') && играИнициализирована && !играОкончена) {
        сохранитьИгру();
    }
    состояние = 'menu';
    показатьЭкран('main-menu');
    обновитьВидимостьHUD();
    обновитьКнопкуПродолжить();
}

function начатьИгру() {
    if (естьСохранение()) {
        if (!confirm('Начать новую игру? Текущее сохранение будет удалено.')) {
            return;
        }
        удалитьСохранение();
    }
    инициализироватьИгру();
    состояние = 'playing';
    показатьЭкран(null);
    обновитьВидимостьHUD();
}

function продолжитьИзСохранения() {
    if (!естьСохранение()) return;
    if (загрузитьИгру()) {
        играИнициализирована = true;
        играОкончена = false;
        состояние = 'playing';
        показатьЭкран(null);
        обновитьВидимостьHUD();
        обновитьИнтерфейс();
    } else {
        alert('Не удалось загрузить сохранение.');
    }
}

function поставитьНаПаузу() {
    if (состояние !== 'playing') return;
    состояние = 'paused';
    показатьЭкран('pause-menu');
    обновитьВидимостьHUD();
}

function продолжитьИгру() {
    if (состояние !== 'paused') return;
    состояние = 'playing';
    показатьЭкран(null);
    обновитьВидимостьHUD();
}

function завершитьИгру(победа) {
    if (играОкончена) return;
    играОкончена = true;
    состояние = 'ended';
    удалитьСохранение();

    const заголовок = $('end-title');
    const подзаголовок = $('end-subtitle');
    if (победа) {
        заголовок.textContent = 'ПОБЕДА';
        заголовок.className = 'end-title win';
        подзаголовок.textContent = 'Бурундия уничтожена. Гурун взят.';
    } else {
        заголовок.textContent = 'ПОРАЖЕНИЕ';
        заголовок.className = 'end-title lose';
        подзаголовок.textContent = 'Гурундия пала. Город потерян.';
    }
    показатьЭкран('end-screen');
    обновитьВидимостьHUD();
}

