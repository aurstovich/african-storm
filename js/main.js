    очки.burun = НАСТРОЙКИ.СТАРТОВЫЕ_ОЧКИ;
    потери.gurun = 0;
    потери.burun = 0;

    сеткаТумана.fill(0);

    построитьГород();
    обновитьВладельцевЗданий(здания);

    создатьОтряд(200, 400, 'gurun', 'infantry');
    создатьОтряд(200, 600, 'gurun', 'sniper');
    создатьОтряд(200, 800, 'gurun', 'infantry');

