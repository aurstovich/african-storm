import { НАСТРОЙКИ } from './config.js';
import { здания, полевые_тела, построитьДорогиИДекор } from './world.js';
import { юниты, Отряд } from './units.js';
import { очки } from './economy.js';
import { потери } from './ui.js';
import { камера, ограничитьКамеру } from './camera.js';
import { сеткаТумана } from './fog.js';

const КЛЮЧ = 'african_storm_save_v1';

export function естьСохранение() {
    try {
        return !!localStorage.getItem(КЛЮЧ);
    } catch (e) {
        return false;
    }
}

export function сохранитьИгру() {
    try {
        const данные = {
            версия: 1,
            время: Date.now(),
            очки: { ...очки },
            потери: { ...потери },
            камера: { x: камера.x, y: камера.y, зум: камера.зум },
            туман: Array.from(сеткаТумана),
            здания: здания.map(з => ({
                x: з.x, y: з.y, ширина: з.ширина, высота: з.высота, тип: з.тип,
                владелец: з.владелец,
                повреждение: з.повреждение,
                оттенок: з.оттенок,
                гарнизонИндексы: з.гарнизон.map(о => юниты.indexOf(о)).filter(i => i >= 0)
            })),
            юниты: юниты.map(ю => ({
                x: ю.x, y: ю.y,
                команда: ю.команда,
                тип: ю.тип,
                здоровье: ю.здоровье,
                раненых: ю.раненых,
                гранаты: ю.гранаты,
                вГарнизонеИндекс: ю.вГарнизоне ? здания.indexOf(ю.вГарнизоне) : -1
            })),
            полевыеТела: полевые_тела.map(т => ({
                x: т.x, y: т.y, угол: т.угол, длина: т.длина,
                команда: т.команда, пятно: т.пятно
            }))
        };
        localStorage.setItem(КЛЮЧ, JSON.stringify(данные));
        return true;
    } catch (e) {
        console.error('Ошибка сохранения:', e);
        return false;
    }
}

export function загрузитьИгру() {
    try {
        const строка = localStorage.getItem(КЛЮЧ);
        if (!строка) return false;
        const данные = JSON.parse(строка);

        // Чистим ВСЁ
        юниты.length = 0;
        здания.length = 0;
        полевые_тела.length = 0;
        сеткаТумана.fill(0);

        // === ВАЖНО: восстанавливаем дороги и декор ===
        // Без этого не будет дорог, деревьев, воронок, обломков, пятен, декоративных трупов.
        построитьДорогиИДекор();

        // Очки и потери
        очки.gurun = данные.очки?.gurun ?? НАСТРОЙКИ.СТАРТОВЫЕ_ОЧКИ;
        очки.burun = данные.очки?.burun ?? НАСТРОЙКИ.СТАРТОВЫЕ_ОЧКИ;
        потери.gurun = данные.потери?.gurun ?? 0;
        потери.burun = данные.потери?.burun ?? 0;

        // Камера
        if (данные.камера) {
            камера.x = данные.камера.x;
            камера.y = данные.камера.y;
            камера.зум = данные.камера.зум;
            ограничитьКамеру();
        }

        // Туман
        if (данные.туман && данные.туман.length === сеткаТумана.length) {
            for (let i = 0; i < данные.туман.length; i++) {
                сеткаТумана[i] = данные.туман[i];
            }
        }

        // Здания
        for (const зД of данные.здания || []) {
            здания.push({
                x: зД.x, y: зД.y, ширина: зД.ширина, высота: зД.высота, тип: зД.тип,
                владелец: зД.владелец,
                повреждение: зД.повреждение,
                оттенок: зД.оттенок,
                гарнизон: []
            });
        }

        // Юниты
        for (const юД of данные.юниты || []) {
            const ю = new Отряд(юД.x, юД.y, юД.команда, юД.тип);
            ю.здоровье = юД.здоровье;
            ю.раненых = юД.раненых;
            ю.гранаты = юД.гранаты;
            юниты.push(ю);

            if (юД.вГарнизонеИндекс >= 0 && здания[юД.вГарнизонеИндекс]) {
                const з = здания[юД.вГарнизонеИндекс];
                з.гарнизон.push(ю);
                ю.вГарнизоне = з;
            }
        }

        // Полевые тела
        for (const тД of данные.полевыеТела || []) {
            полевые_тела.push({
                x: тД.x, y: тД.y, угол: тД.угол, длина: тД.длина,
                команда: тД.команда, пятно: тД.пятно
            });
        }

        // Обновляем владельцев зданий
        for (const з of здания) {
            const живые = з.гарнизон.filter(о => о.жив);
            з.гарнизон = живые;
            if (живые.length === 0) з.владелец = null;
            else з.владелец = живые[0].команда;
        }

        return true;
    } catch (e) {
        console.error('Ошибка загрузки:', e);
        return false;
    }
}

export function удалитьСохранение() {
    try {
        localStorage.removeItem(КЛЮЧ);
    } catch (e) {}
}

export function времяСохранения() {
    try {
        const строка = localStorage.getItem(КЛЮЧ);
        if (!строка) return null;
        const данные = JSON.parse(строка);
        return данные.время || null;
    } catch (e) {
        return null;
    }
}