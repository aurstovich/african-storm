function нарисоватьЗдания() {
    const отсортированные = [...здания].sort((a, b) => (a.y + a.высота) - (b.y + b.высота));
    for (const з of отсортированные) {
        const cx = з.x + з.ширина / 2;
        const cy = з.y + з.высота / 2;

        if (з.владелец && разведанаТочка(cx, cy)) {
            const цвет = з.владелец === 'gurun' ? '74,144,217' : '217,74,74';
            const градиент = контекст.createRadialGradient(cx, cy, 0, cx, cy, НАСТРОЙКИ.РАДИУС_БОНУСА);
            градиент.addColorStop(0, `rgba(${цвет},0.1)`);
            градиент.addColorStop(1, `rgba(${цвет},0)`);
            контекст.fillStyle = градиент;
            контекст.beginPath();
            контекст.arc(cx, cy, НАСТРОЙКИ.РАДИУС_БОНУСА, 0, Math.PI * 2);
            контекст.fill();
        }

        контекст.fillStyle = 'rgba(0,0,0,0.6)';
        контекст.fillRect(з.x + 8, з.y + 8, з.ширина, з.высота);

        if (з.тип === 'house') нарисоватьКрышуДома(з);
        else if (з.тип === 'admin') нарисоватьКрышуАдминистрации(з);
        else нарисоватьКрышуЗавода(з);

        if (з.владелец) {
            контекст.strokeStyle = з.владелец === 'gurun' ? '#4a90d9' : '#d94a4a';
            контекст.lineWidth = 3 / камера.зум;
            контекст.strokeRect(з.x - 2, з.y - 2, з.ширина + 4, з.высота + 4);
        }

        нарисоватьГарнизонНаКрыше(з);
    }
}

function нарисоватьКрышуДома(з) {
    const затемнение = 1 - з.повреждение * 0.6;
    const r = Math.floor((120 + з.оттенок) * затемнение);
    const g = Math.floor((70 + з.оттенок) * затемнение);
    const b = Math.floor(50 * затемнение);
    контекст.fillStyle = `rgb(${r},${g},${b})`;
    контекст.fillRect(з.x, з.y, з.ширина, з.высота);
    контекст.strokeStyle = `rgba(0,0,0,0.25)`;
    контекст.lineWidth = 1 / камера.зум;
    for (let i = 1; i < 4; i++) {
        const y = з.y + (з.высота / 4) * i;
        контекст.beginPath();
        контекст.moveTo(з.x, y);
        контекст.lineTo(з.x + з.ширина, y);
        контекст.stroke();
    }
    контекст.strokeStyle = 'rgba(0,0,0,0.5)';
    контекст.lineWidth = 2 / камера.зум;
    контекст.beginPath();
    контекст.moveTo(з.x + 4, з.y + з.высота / 2);
    контекст.lineTo(з.x + з.ширина - 4, з.y + з.высота / 2);
    контекст.stroke();
    контекст.fillStyle = 'rgba(255,220,180,0.08)';
    контекст.fillRect(з.x, з.y, з.ширина, з.высота / 2);
    контекст.fillStyle = 'rgba(0,0,0,0.25)';
    контекст.fillRect(з.x, з.y + з.высота / 2, з.ширина, з.высота / 2);
    if (з.повреждение > 0.25) {
        контекст.fillStyle = `rgba(10,5,3,${з.повреждение * 0.7})`;
        контекст.beginPath();
        контекст.arc(з.x + з.ширина * 0.3, з.y + з.высота * 0.3, з.ширина * 0.18, 0, Math.PI * 2);
        контекст.fill();
        контекст.beginPath();
        контекст.arc(з.x + з.ширина * 0.7, з.y + з.высота * 0.65, з.ширина * 0.14, 0, Math.PI * 2);
        контекст.fill();
        if (з.повреждение > 0.5) {
            контекст.fillStyle = '#050302';
            контекст.beginPath();
            контекст.arc(з.x + з.ширина * 0.55, з.y + з.высота * 0.45, з.ширина * 0.12, 0, Math.PI * 2);
            контекст.fill();
        }
    }
    контекст.strokeStyle = '#0a0605';
    контекст.lineWidth = 1.5 / камера.зум;
    контекст.strokeRect(з.x, з.y, з.ширина, з.высота);
}

