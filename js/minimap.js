import { НАСТРОЙКИ } from './config.js';
import { здания } from './world.js';
import { камера, экранВМир, ограничитьКамеру, ШИРИНА_ЭКРАНА, ВЫСОТА_ЭКРАНА } from './camera.js';
import { виднаТочка } from './fog.js';

let _юниты = null;

export function подключитьМиниКарту(юниты) {
    _юниты = юниты;
}

export function нарисоватьМиниКарту(контекст) {
    // Настройки мини-карты
    const МИНИ_РАЗМЕР = 180; // Размер на экране
    const ОТСТУП_СПРАВА = 12;
    const ОТСТУП_СНИЗУ = 220; // Чтобы не перекрывать магазин
    
    // Позиция на экране (правый нижний угол)
    const sx = ШИРИНА_ЭКРАНА - МИНИ_РАЗМЕР - ОТСТУП_СПРАВА;
    const sy = ВЫСОТА_ЭКРАНА - МИНИ_РАЗМЕР - ОТСТУП_СНИЗУ;
    
    // На мобильных прячем миникарту, если экран слишком маленький
    if (ШИРИНА_ЭКРАНА < 600) return;

    // Масштаб: мир -> мини-карта
    const масштаб = МИНИ_РАЗМЕР / НАСТРОЙКИ.РАЗМЕР_МИРА;

    контекст.save();
    контекст.setTransform(1, 0, 0, 1, 0, 0); // Сбрасываем трансформации

    // Фон
    контекст.fillStyle = 'rgba(10, 14, 10, 0.85)';
    контекст.fillRect(sx, sy, МИНИ_РАЗМЕР, МИНИ_РАЗМЕР);
    
    // Рамка
    контекст.strokeStyle = '#4a5f3a';
    контекст.lineWidth = 2;
    контекст.strokeRect(sx, sy, МИНИ_РАЗМЕР, МИНИ_РАЗМЕР);

    // Здания
    for (const з of здания) {
        const mx = sx + з.x * масштаб;
        const my = sy + з.y * масштаб;
        const mw = з.ширина * масштаб;
        const mh = з.высота * масштаб;

        if (з.владелец === 'gurun') контекст.fillStyle = '#4a90d9';
        else if (з.владелец === 'burun') контекст.fillStyle = '#d94a4a';
        else контекст.fillStyle = '#5a5a5a';

        контекст.fillRect(mx, my, mw, mh);
    }

    // Юниты
    if (_юниты) {
        for (const ю of _юниты) {
            if (!ю.жив || ю.вГарнизоне) continue;
            
            // Показываем только разведанных врагов или своих
            const поз = ю.позиция;
            if (ю.команда === 'gurun' || виднаТочка(поз.x, поз.y)) {
                const mx = sx + поз.x * масштаб;
                const my = sy + поз.y * масштаб;

                контекст.beginPath();
                контекст.arc(mx, my, 2, 0, Math.PI * 2);
                контекст.fillStyle = ю.команда === 'gurun' ? '#6ab0f0' : '#f07070';
                контекст.fill();
            }
        }
    }

    // Прямоугольник текущего обзора камеры
    const видимаяШирина = (ШИРИНА_ЭКРАНА / камера.зум) * масштаб;
    const видимаяВысота = (ВЫСОТА_ЭКРАНА / камера.зум) * масштаб;
    const кx = sx + камера.x * масштаб;
    const кy = sy + камера.y * масштаб;

    контекст.strokeStyle = '#9fdf5f';
    контекст.lineWidth = 1.5;
    контекст.strokeRect(кx, кy, видимаяШирина, видимаяВысота);

    контекст.restore();
}

// Обработка клика по мини-карте (вызывается из input.js)
export function обработатьКликПоМиниКарте(экранX, экранY) {
    const МИНИ_РАЗМЕР = 180;
    const ОТСТУП_СПРАВА = 12;
    const ОТСТУП_СНИЗУ = 220;

    // Если мобильный — миникарта скрыта
    if (ШИРИНА_ЭКРАНА < 600) return false;

    const sx = ШИРИНА_ЭКРАНА - МИНИ_РАЗМЕР - ОТСТУП_СПРАВА;
    const sy = ВЫСОТА_ЭКРАНА - МИНИ_РАЗМЕР - ОТСТУП_СНИЗУ;

    // Попал ли клик в область миникарты?
    if (экранX >= sx && экранX <= sx + МИНИ_РАЗМЕР &&
        экранY >= sy && экранY <= sy + МИНИ_РАЗМЕР) {
        
        // Переводим клик в мировые координаты
        const масштаб = МИНИ_РАЗМЕР / НАСТРОЙКИ.РАЗМЕР_МИРА;
        const мирX = (экранX - sx) / масштаб;
        const мирY = (экранY - sy) / масштаб;

        // Центрируем камеру на этой точке
        камера.x = мирX - (ШИРИНА_ЭКРАНА / камера.зум) / 2;
        камера.y = мирY - (ВЫСОТА_ЭКРАНА / камера.зум) / 2;
        ограничитьКамеру();
        
        return true; // Клик обработан
    }
    return false; // Клик не по миникарте
}