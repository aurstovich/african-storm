export const здания = [];
export const дороги = [];
export const деревья = [];
export const воронки = [];
export const трупы = [];
export const обломки = [];
export const пятна = [];
export const полевые_тела = [];

// НОВОЕ: Кустарники, трава и сгоревшая техника
export const кустарники = [];
export const сгоревшая_техника = [];

function создатьЗдание(x, y, ширина, высота, тип) {
    const повреждение = Math.random() * 0.7;
    return {
        x, y, ширина, высота, тип,
        владелец: null,
        гарнизон: [],
        повреждение,
        оттенок: Math.random() * 30 - 15
    };
}

// === Генерирует ТОЛЬКО дороги и декор (без зданий) ===
export function построитьДорогиИДекор() {
    дороги.length = 0;
    деревья.length = 0;
    воронки.length = 0;
    трупы.length = 0;
    обломки.length = 0;
    пятна.length = 0;
    кустарники.length = 0;
    сгоревшая_техника.length = 0;

    // Дороги
    for (let i = 0; i < НАСТРОЙКИ.РАЗМЕР_МИРА; i += 200) {
        дороги.push({ x: i, y: 0, ш: 40, в: НАСТРОЙКИ.РАЗМЕР_МИРА, тип: 'вертикальная' });
        дороги.push({ x: 0, y: i, ш: НАСТРОЙКИ.РАЗМЕР_МИРА, в: 40, тип: 'горизонтальная' });
    }

    // Обычные деревья
    for (let i = 0; i < 40; i++) {
        деревья.push({
            x: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            y: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            радиус: 5 + Math.random() * 5,
            сгоревшее: false
        });
    }

    // НОВОЕ: Сгоревшие деревья (примерно 20% от всех)
    for (let i = 0; i < 10; i++) {
        деревья.push({
            x: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            y: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            радиус: 4 + Math.random() * 4,
            сгоревшее: true
        });
    }

    // НОВОЕ: Кустарники и высокая трава (для реализма)
    for (let i = 0; i < 200; i++) {
        кустарники.push({
            x: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            y: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            радиус: 2 + Math.random() * 4,
            цвет: Math.random() < 0.1 ? '#2a1a10' : (Math.random() < 0.5 ? '#2e4a1e' : '#3a5a28') // 10% сгоревшие
        });
    }

    // Воронки
    for (let i = 0; i < 60; i++) {
        воронки.push({
            x: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            y: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            радиус: 8 + Math.random() * 18,
            глубина: 0.3 + Math.random() * 0.4
        });
    }

    // Декоративные трупы
    for (let i = 0; i < 40; i++) {
        let x, y;
        if (Math.random() < 0.5) { x = 500 + Math.random() * 1000; y = 500 + Math.random() * 1000; }
        else { x = Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА; y = Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА; }
        трупы.push({
            x, y,
            угол: Math.random() * Math.PI * 2,
            длина: 8 + Math.random() * 4,
            сторона: Math.random() < 0.5 ? 'gurun' : 'burun',
            пятно: 6 + Math.random() * 6
        });
    }

    // Обломки
    for (let i = 0; i < 120; i++) {
        обломки.push({
            x: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            y: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            угол: Math.random() * Math.PI * 2,
            длина: 2 + Math.random() * 6,
            ширина: 1 + Math.random() * 2,
            цвет: Math.random() < 0.5 ? '#3a2e26' : '#4a3e36'
        });
    }

    // Пятна (копоть, гарь)
    for (let i = 0; i < 30; i++) {
        пятна.push({
            x: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            y: Math.random() * НАСТРОЙКИ.РАЗМЕР_МИРА,
            радиус: 15 + Math.random() * 30,
            альфа: 0.15 + Math.random() * 0.2
        });
    }

    // НОВОЕ: Сгоревшая техника (3 танка и 3 БТРа)
    // Разбрасываем по карте, но ближе к дорогам
    for (let i = 0; i < 3; i++) {
        сгоревшая_техника.push({
            x: 300 + Math.random() * (НАСТРОЙКИ.РАЗМЕР_МИРА - 600),
            y: 300 + Math.random() * (НАСТРОЙКИ.РАЗМЕР_МИРА - 600),
            тип: 'танк',
            угол: Math.random() * Math.PI * 2,
            длина: 45, ширина: 25 // Примерные размеры сверху
        });
    }
    for (let i = 0; i < 3; i++) {
        сгоревшая_техника.push({
            x: 300 + Math.random() * (НАСТРОЙКИ.РАЗМЕР_МИРА - 600),
            y: 300 + Math.random() * (НАСТРОЙКИ.РАЗМЕР_МИРА - 600),
            тип: 'бтр',
            угол: Math.random() * Math.PI * 2,
            длина: 40, ширина: 20
        });
    }
}

// Конфигурация карт
const КАРТЫ = {
    'gurun': {
        дороги: (РАЗМЕР) => {
            const дороги = [];
            for (let i = 0; i < РАЗМЕР; i += 200) {
                дороги.push({ x: i, y: 0, ш: 40, в: РАЗМЕР, тип: 'вертикальная' });
                дороги.push({ x: 0, y: i, ш: РАЗМЕР, в: 40, тип: 'горизонтальная' });
            }
            return дороги;
        },
        здания: (РАЗМЕР) => {
            const здания = [];
            for (let x = 100; x < РАЗМЕР; x += 200) {
                for (let y = 100; y < РАЗМЕР; y += 200) {
                    if (x > 800 && x < 1200 && y > 800 && y < 1200) continue;
                    if (Math.random() > 0.3) здания.push(создатьЗдание(x, y, 80, 80, 'house'));
                }
            }
            const админ = создатьЗдание(900, 900, 200, 200, 'admin');
            админ.повреждение = 0.4;
            здания.push(админ);
            здания.push(создатьЗдание(300, 1500, 150, 150, 'factory'));
            здания.push(создатьЗдание(1550, 400, 150, 150, 'factory'));
            return здания;
        }
    }
};

export function построитьГород(названиеКарты = 'gurun') {
    const карта = КАРТЫ[названиеКарты] || КАРТЫ['gurun'];
    
    построитьДорогиИДекор();
    
    if (карта.дороги) {
        дороги.length = 0;
        дороги.push(...карта.дороги(НАСТРОЙКИ.РАЗМЕР_МИРА));
    }
    
    здания.length = 0;
    здания.push(...карта.здания(НАСТРОЙКИ.РАЗМЕР_МИРА));
}

export function добавитьПолевоеТело(x, y, команда) {
    полевые_тела.push({
        x: x + (Math.random() - 0.5) * 30,
        y: y + (Math.random() - 0.5) * 30,
        угол: Math.random() * Math.PI * 2,
        длина: 7 + Math.random() * 4,
        команда,
        пятно: 5 + Math.random() * 5,
        создано: performance.now()
    });
    звукСмертиБойца();
}