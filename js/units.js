export function подключитьЗависимости({ учестьПотери, обновитьИнтерфейс, войтиВГарнизон, выйтиИзГарнизона, добавитьОтложенныйВзрыв }) {
    _учестьПотери = учестьПотери;
    _обновитьИнтерфейс = обновитьИнтерфейс;
    _войтиВГарнизон = войтиВГарнизон;
    _выйтиИзГарнизона = выйтиИзГарнизона;
    _добавитьОтложенныйВзрыв = добавитьОтложенныйВзрыв;
}

export const юниты = [];

function точкаВЗдании(x, y, радиусОтряда) {
    for (const з of здания) {
        if (x > з.x - радиусОтряда && x < з.x + з.ширина + радиусОтряда &&
            y > з.y - радиусОтряда && y < з.y + з.высота + радиусОтряда) return з;
    }
    return null;
}

function прямойПутьСвободен(x1, y1, x2, y2) {
    const шаг = 10, dx = x2 - x1, dy = y2 - y1;
    const расстояние = Math.hypot(dx, dy), шагов = Math.ceil(расстояние / шаг);
    for (let i = 1; i <= шагов; i++) {
        const t = i / шагов;
        if (точкаВЗдании(x1 + dx * t, y1 + dy * t, 5)) return false;
    }
    return true;
}

function найтиТочкуОбхода(отX, отY, доХ, доУ) {
    const dx = доХ - отX, dy = доУ - отY;
    const расстояние = Math.hypot(dx, dy), шагов = Math.ceil(расстояние / 10);
    let блок = null;
    for (let i = 1; i < шагов; i++) {
        const з = точкаВЗдании(отX + dx * (i/шагов), отY + dy * (i/шагов), 5);
        if (з) { блок = з; break; }
    }
    if (!блок) return null;
    const отступ = 20;
    const углы = [
        { x: блок.x - отступ, y: блок.y - отступ },
        { x: блок.x + блок.ширина + отступ, y: блок.y - отступ },
        { x: блок.x + блок.ширина + отступ, y: блок.y + блок.высота + отступ },
        { x: блок.x - отступ, y: блок.y + блок.высота + отступ }
    ];
    let лучшийУгол = null, лучшаяДистанция = Infinity;
    for (const угол of углы) {
        if (точкаВЗдании(угол.x, угол.y, 5)) continue;
        if (!прямойПутьСвободен(отX, отY, угол.x, угол.y)) continue;
        const d = Math.hypot(угол.x - доХ, угол.y - доУ);
        if (d < лучшаяДистанция) { лучшаяДистанция = d; лучшийУгол = угол; }
    }
    return лучшийУгол;
}

export class Отряд {
    constructor(x, y, команда, тип) {
        this.x = x;
        this.y = y;
        this.команда = команда;
        this.тип = тип;
        this.выделен = false;

        this.цель = null;
        this.цельАтаки = null;
        this.перезарядка = 0;

        this.вГарнизоне = null;
        this.приказВойтиВ = null;
        this.накопленныйУрон = 0;
        this.обходнаяТочка = null;

        // Для танка: угол поворота (в радианах)
        this.уголПоворота = 0;
        this.целевойУгол = 0;

        const н = НАСТРОЙКИ.ЮНИТЫ[тип];
        if (!н) throw new Error('Неизвестный тип юнита: ' + тип);

        this.гранаты = н.ГРАНАТ || 0;
        this.перезарядкаГранаты = 0;
        this.техника = н.ТЕХНИКА || false;

        this.максЗдоровье = н.ЗДОРОВЬЕ;
        this.здоровье = н.ЗДОРОВЬЕ;
        this.раненых = 0;
        this.радиус = н.РАДИУС;
        this.скорость = н.СКОРОСТЬ;
        this.базоваяДальность = н.ДАЛЬНОСТЬ;
        this.обнаружение = н.ОБНАРУЖЕНИЕ;
        this.урон = н.УРОН;
        this.перезарядка_макс = н.ПЕРЕЗАРЯДКА;

        this.метка = н.МЕТКА;
        this.цветТрассера = команда === 'gurun' ? '#9cd0ff' : '#ff9c9c';
    }

    get жив() { return this.здоровье > 0; }

    get дальность() {
        if (this.вГарнизоне) return this.базоваяДальность * НАСТРОЙКИ.БОНУС_ДАЛЬНОСТИ_ГАРНИЗОНА;
        return this.базоваяДальность;
    }

    get позиция() {
        if (this.вГарнизоне) {
            return { x: this.вГарнизоне.x + this.вГарнизоне.ширина / 2, y: this.вГарнизоне.y + this.вГарнизоне.высота / 2 };
        }
        return { x: this.x, y: this.y };
    }

    бонусЗащиты() {
        if (this.вГарнизоне) return НАСТРОЙКИ.БОНУС_ЗАЩИТЫ_ГАРНИЗОНА;
        let бонус = 0;
        const поз = this.позиция;
        for (const з of здания) {
            if (з.владелец !== this.команда) continue;
            if (Math.hypot(з.x + з.ширина / 2 - поз.x, з.y + з.высота / 2 - поз.y) <= НАСТРОЙКИ.РАДИУС_БОНУСА) бонус = Math.max(бонус, 0.3);
        }
        return бонус;
    }

    найтиБлижайшегоВрага(всеЮниты) {
        let лучший = null, лучшаяД = Infinity;
        const поз = this.позиция;
        for (const враг of всеЮниты) {
            if (!враг.жив || враг.команда === this.команда) continue;
            const вп = враг.позиция;
            if (!виднаТочка(вп.x, вп.y)) continue;
            const d = Math.hypot(вп.x - поз.x, вп.y - поз.y);
            if (d >= лучшаяД) continue;
            if (!линияОгняСвободна(поз.x, поз.y, вп.x, вп.y, this, враг)) continue;
            лучшаяД = d; лучший = враг;
        }
        return { враг: лучший, дистанция: лучшаяД };
    }

    обновить(всеЮниты, кадровПрошло) {
        if (!this.жив) return;
        if (this.перезарядка > 0) this.перезарядка -= кадровПрошло;
        if (this.перезарядкаГранаты > 0) this.перезарядкаГранаты -= кадровПрошло;

        if (this.вГарнизоне) { this.стрелятьПоВрагу(всеЮниты); return; }
        if (this.приказВойтиВ) { this.идтиКЗданию(кадровПрошло); return; }
        
        this.двигатьсяКЦели(кадровПрошло);
        this.стрелятьПоВрагу(всеЮниты);

        // === ПОВОРОТ ТАНКА ===
        if (this.техника) {
            // Если движется — поворачиваем в сторону движения
            if (this.цель || (this.цельАтаки && this.цельАтаки.жив)) {
                let targetX = this.цель ? this.цель.x : this.цельАтаки.позиция.x;
                let targetY = this.цель ? this.цель.y : this.цельАтаки.позиция.y;
                this.целевойУгол = Math.atan2(targetY - this.y, targetX - this.x);
            }
            
            // Плавно поворачиваем
            let diff = this.целевойУгол - this.уголПоворота;
            while (diff > Math.PI) diff -= Math.PI * 2;
            while (diff < -Math.PI) diff += Math.PI * 2;
            this.уголПоворота += diff * 0.1; // Скорость поворота
        }
    }

    идтиКЗданию(кадровПрошло) {
        if (this.техника) { this.приказВойтиВ = null; return; }

        const з = this.приказВойтиВ;
        if (!з) return;
        const cx = з.x + з.ширина / 2, cy = з.y + з.высота / 2;
        const dx = cx - this.x, dy = cy - this.y, дистанция = Math.hypot(dx, dy);

        if (дистанция < 15) {
            if (_войтиВГарнизон) _войтиВГарнизон(this, з);
            this.приказВойтиВ = null;
            return;
        }

        const шаг = this.скорость * кадровПрошло, k = Math.min(1, шаг / дистанция);
        this.x += dx * k; this.y += dy * k;
    }

    двигатьсяКЦели(кадровПрошло) {
        let точка = null, этоАтака = false;
        if (this.цельАтаки && this.цельАтаки.жив) {
            const поз = this.позиция, цп = this.цельАтаки.позиция;
            if (Math.hypot(цп.x - поз.x, цп.y - поз.y) > this.дальность * 0.9) {
                точка = { x: цп.x, y: цп.y }; этоАтака = true;
            }
        } else if (this.цельАтаки && !this.цельАтаки.жив) this.цельАтаки = null;
        if (!точка && this.цель) точка = this.цель;
        if (!точка) return;

        if (!this.обходнаяТочка && !прямойПутьСвободен(this.x, this.y, точка.x, точка.y)) {
            const угол = найтиТочкуОбхода(this.x, this.y, точка.x, точка.y);
            if (угол) this.обходнаяТочка = угол;
        }

        let текущаяЦель = this.обходнаяТочка || точка;
        const dx = текущаяЦель.x - this.x, dy = текущаяЦель.y - this.y, d = Math.hypot(dx, dy);

        if (d > 5) {
            const шаг = this.скорость * кадровПрошло, k = Math.min(1, шаг / d);
            let новаяX = this.x + dx * k, новаяY = this.y + dy * k;
            const мыВнутри = точкаВЗдании(this.x, this.y, this.радиус);
            const столкновение = мыВнутри ? null : точкаВЗдании(новаяX, новаяY, this.радиус);
            
            if (столкновение) {
                const свобX = !точкаВЗдании(this.x + dx * k, this.y, this.радиус);
                const свобY = !точкаВЗдании(this.x, this.y + dy * k, this.радиус);
                if (свобX && !свобY) this.x += dx * k;
                else if (свобY && !свобX) this.y += dy * k;
                else if (свобX && свобY) { this.x += dx * k; this.y += dy * k; }
                else this.обходнаяТочка = null;
            } else { this.x = новаяX; this.y = новаяY; }
        } else {
            if (this.обходнаяТочка) this.обходнаяТочка = null;
            else if (!этоАтака) this.цель = null;
        }
    }

    стрелятьПоВрагу(всеЮниты) {
        let цель = null;
        const поз = this.позиция;
        if (this.цельАтаки && this.цельАтаки.жив) {
            const цп = this.цельАтаки.позиция;
            if (Math.hypot(цп.x - поз.x, цп.y - поз.y) <= this.дальность && виднаТочка(цп.x, цп.y) && линияОгняСвободна(поз.x, поз.y, цп.x, цп.y, this, this.цельАтаки)) цель = this.цельАтаки;
        }
        if (!цель) {
            const { враг, дистанция } = this.найтиБлижайшегоВрага(всеЮниты);
            if (враг && дистанция <= this.обнаружение && дистанция <= this.дальность) цель = враг;
        }

        if (цель && this.перезарядка <= 0) {
            if (this.тип === 'infantry' && this.гранаты > 0 && this.перезарядкаГранаты <= 0 && Math.hypot(цель.позиция.x - поз.x, цель.позиция.y - поз.y) <= НАСТРОЙКИ.РАДИУС_БРОСКА_ГРАНАТЫ) {
                this.броситьГранату(цель, всеЮниты);
                this.перезарядка = this.перезарядка_макс;
                this.перезарядкаГранаты = НАСТРОЙКИ.ПЕРЕЗАРЯДКА_ГРАНАТЫ;
            } else {
                this.выстрелить(цель, всеЮниты);
                this.перезарядка = this.перезарядка_макс;
            }
        }
    }

    броситьГранату(цель, всеЮниты) {
        if (this.гранаты <= 0) return;
        this.гранаты -= 1;
        const поз = this.позиция, цп = цель.позиция;
        let точкаВзрыва;
        const попала = Math.random() < НАСТРОЙКИ.ШАНС_ПОПАДАНИЯ_ГРАНАТЫ;

        if (попала) точкаВзрыва = { x: цп.x, y: цп.y };
        else {
            const угол = Math.random() * Math.PI * 2, смещение = 30 + Math.random() * 30;
            точкаВзрыва = { x: цп.x + Math.cos(угол) * смещение, y: цп.y + Math.sin(угол) * смещение };
        }

        добавитьГранатаЛетящую({ x: поз.x, y: поз.y - 10 }, точкаВзрыва);
        if (_добавитьОтложенныйВзрыв) _добавитьОтложенныйВзрыв(this, точкаВзрыва, 30);
        добавитьТекст(поз.x, поз.y - 40, попала ? 'ГРАНАТА!' : 'мимо...', попала ? '#ffcc66' : '#a08060');
    }

    взорватьГранату(x, y, всеЮниты) {
        звукВзрываГранаты();
        добавитьВзрыв(x, y, '#ff8040', НАСТРОЙКИ.РАДИУС_ПОРАЖЕНИЯ_ГРАНАТЫ);
        добавитьВзрыв(x, y, '#ffcc80', НАСТРОЙКИ.РАДИУС_ПОРАЖЕНИЯ_ГРАНАТЫ * 0.5);

        for (const враг of всеЮниты) {
            if (!враг.жив || враг.команда === this.команда) continue;
            const вп = враг.позиция;
            const d = Math.hypot(вп.x - x, вп.y - y);
            if (d <= НАСТРОЙКИ.РАДИУС_ПОРАЖЕНИЯ_ГРАНАТЫ) {
                const близко = d < НАСТРОЙКИ.РАДИУС_ПОРАЖЕНИЯ_ГРАНАТЫ * 0.5;
                if (близко || Math.random() < 0.5) враг.мгновеннаяСмерть(всеЮниты);
                else враг.получитьУрон(1, всеЮниты);
            }
        }
    }

    выстрелить(враг, всеЮниты) {
        const поз = this.позиция, цп = враг.позиция;
        добавитьТрассер({ x: поз.x, y: поз.y - 5 }, { x: цп.x, y: цп.y - 5 }, this.цветТрассера);

        if (this.тип === 'sniper') звукВыстрелаСнайпера();
        else звукВыстрелаПехоты();

        const бонус = враг.бонусЗащиты();

        if (this.тип === 'sniper') {
            const ранен = Math.random() < НАСТРОЙКИ.ШАНС_РАНЕНИЯ_ОТ_СНАЙПЕРА;
            if (ранен && бонус < 0.5) {
                враг.получитьУрон(1, всеЮниты);
                добавитьТекст(цп.x, цп.y - 40, 'ранен', '#e0a860');
            } else {
                враг.мгновеннаяСмерть(всеЮниты);
                добавитьТекст(цп.x, цп.y - 40, 'СНАЙПЕР!', '#ff3030');
            }
        } else {
            const шанс = this.тип === 'tank' ? 0.5 : НАСТРОЙКИ.ШАНС_МГНОВЕННОЙ_СМЕРТИ_ПЕХОТЫ * (1 - бонус);
            if (Math.random() < шанс) {
                враг.мгновеннаяСмерть(всеЮниты);
                добавитьТекст(цп.x, цп.y - 40, this.тип === 'tank' ? 'ТАНК!' : 'в голову!', '#ff8080');
            } else {
                враг.получитьУрон(this.урон, всеЮниты);
            }
        }
        if (бонус > 0) добавитьТекст(цп.x, цп.y - 30, 'защ.', '#7fff7f');
    }

    получитьУрон(урон, всеЮниты) {
        if (this.техника) {
            this.здоровье -= урон * 0.2;
            if (this.здоровье <= 0) {
                this.здоровье = 0;
                this.умереть(всеЮниты);
            }
            if (_обновитьИнтерфейс) _обновитьИнтерфейс();
            return;
        }

        this.накопленныйУрон += урон;
        while (this.накопленныйУрон >= 1) {
            this.накопленныйУрон -= 1;
            const здоровых = this.здоровье - this.раненых;
            if (здоровых > 0) {
                this.раненых += 1;
                добавитьТекст(this.позиция.x, this.позиция.y - 30, '−1 ранен', '#e0a860');
            } else if (this.раненых > 0) {
                this.раненых -= 1;
                this.здоровье -= 1;
                if (_учестьПотери) _учестьПотери(this.команда, 1);
                добавитьТекст(this.позиция.x, this.позиция.y - 30, '−1 убит', '#ff6060');
                добавитьПолевоеТело(this.позиция.x, this.позиция.y, this.команда);
                if (this.здоровье <= 0) { this.умереть(всеЮниты); return; }
            }
        }
        if (_обновитьИнтерфейс) _обновитьИнтерфейс();
    }

    мгновеннаяСмерть(всеЮниты) {
        if (this.техника) return;

        const здоровых = this.здоровье - this.раненых;
        if (здоровых > 0) {
            this.здоровье -= 1;
            if (_учестьПотери) _учестьПотери(this.команда, 1);
            добавитьТекст(this.позиция.x, this.позиция.y - 30, '−1 убит', '#ff3030');
            добавитьПолевоеТело(this.позиция.x, this.позиция.y, this.команда);
        } else if (this.раненых > 0) {
            this.раненых -= 1;
            this.здоровье -= 1;
            if (_учестьПотери) _учестьПотери(this.команда, 1);
            добавитьТекст(this.позиция.x, this.позиция.y - 30, '−1 добит', '#ff3030');
            добавитьПолевоеТело(this.позиция.x, this.позиция.y, this.команда);
        }
        if (this.здоровье <= 0) this.умереть(всеЮниты);
        if (_обновитьИнтерфейс) _обновитьИнтерфейс();
    }

    умереть(всеЮниты) {
        if (this.вГарнизоне && _выйтиИзГарнизона) _выйтиИзГарнизона(this);
        const цвет = this.команда === 'gurun' ? '#4a90d9' : '#d94a4a';
        добавитьАнимациюСмерти(this.x, this.y, цвет);
        добавитьВзрыв(this.x, this.y, '#ff7a2a', this.радиус * 2);

        if (!this.техника) {
            for (let i = 0; i < 3; i++) добавитьПолевоеТело(this.x, this.y, this.команда);
        }

        this.выделен = false;
        this.цель = null;
        this.цельАтаки = null;
        this.приказВойтиВ = null;
        for (const ю of всеЮниты) if (ю.цельАтаки === this) ю.цельАтаки = null;
        if (_обновитьИнтерфейс) _обновитьИнтерфейс();
    }

    отрисовать(контекст, камера) {
        if (this.вГарнизоне) return;
        const поз = this.позиция;
        this.отрисоватьМаркер(контекст, камера, поз.x, поз.y, this.радиус);
    }

    отрисоватьМаркер(контекст, камера, x, y, радиус) {
        const цветКоманды = this.команда === 'gurun' ? '#4a90d9' : '#d94a4a';
        const R = радиус;
        const бонус = this.бонусЗащиты();

        контекст.save();
        контекст.translate(x, y);
        
        // Для танка поворачиваем весь контекст
        if (this.техника) {
            контекст.rotate(this.уголПоворота);
        }

        // Тень
        контекст.beginPath();
        контекст.ellipse(0, R * 0.4, R * 1.5, R * 0.6, 0, 0, Math.PI * 2);
        контекст.fillStyle = 'rgba(0,0,0,0.5)';
        контекст.fill();

        if (this.техника) {
            // === ОТРИСОВКА ТАНКА (с поворотом) ===
            const ш = R * 2.2, в = R * 1.2;
            
            // Гусеницы
            контекст.fillStyle = '#111';
            контекст.fillRect(-ш/2, -в/2 - 4 / камера.зум, ш, 6 / камера.зум);
            контекст.fillRect(-ш/2, в/2 - 2 / камера.зум, ш, 6 / камера.зум);

            // Корпус
            контекст.fillStyle = '#2a4a2a';
            контекст.fillRect(-ш/2, -в/2, ш, в);
            контекст.strokeStyle = '#1a2a1a';
            контекст.lineWidth = 2 / камера.зум;
            контекст.strokeRect(-ш/2, -в/2, ш, в);

            // Башня
            контекст.fillStyle = '#1a3a1a';
            контекст.beginPath();
            контекст.arc(0, 0, R * 0.6, 0, Math.PI * 2);
            контекст.fill();
            контекст.strokeStyle = '#0a1a0a';
            контекст.stroke();

            // Ствол
            контекст.fillStyle = '#111';
            контекст.fillRect(R * 0.4, -2 / камера.зум, R * 1.4, 4 / камера.зум);
            контекст.strokeStyle = '#000';
            контекст.strokeRect(R * 0.4, -2 / камера.зум, R * 1.4, 4 / камера.зум);

            // Детали (люк, ящики)
            контекст.fillStyle = '#3a5a3a';
            контекст.fillRect(-ш/2 + 5, -в/2 + 5, 8, 8);
            контекст.fillRect(-ш/2 + 5, в/2 - 13, 8, 8);

        } else {
            // === ОТРИСОВКА ПЕХОТЫ И СНАЙПЕРОВ ===
            const ш = R * 2, в = R * 1.4;
            контекст.fillStyle = 'rgba(20,26,18,0.95)';
            контекст.strokeStyle = цветКоманды;
            контекст.lineWidth = 2 / камера.зум;
            контекст.beginPath();
            контекст.rect(-ш/2, -в/2, ш, в);
            контекст.fill();
            контекст.stroke();

            контекст.strokeStyle = '#d0d8c8';
            контекст.fillStyle = '#d0d8c8';
            контекст.lineWidth = 1.5 / камера.зум;
            if (this.тип === 'infantry') {
                const d = R * 0.6;
                контекст.beginPath();
                контекст.moveTo(-d, -d * 0.7); контекст.lineTo(d, d * 0.7);
                контекст.moveTo(d, -d * 0.7); контекст.lineTo(-d, d * 0.7);
                контекст.stroke();
            } else {
                контекст.beginPath(); контекст.arc(0, 0, R * 0.5, 0, Math.PI * 2); контекст.stroke();
                контекст.beginPath(); контекст.arc(0, 0, R * 0.12, 0, Math.PI * 2); контекст.fill();
            }
        }

        // Треугольник команды (не поворачиваем для танка, чтобы было видно)
        if (!this.техника) {
            const hTriangle = R * 1.4;
            контекст.fillStyle = цветКоманды;
            контекст.beginPath();
            контекст.moveTo(0, -hTriangle/2 - 4);
            контекст.lineTo(-5, -hTriangle/2 - 10);
            контекст.lineTo(5, -hTriangle/2 - 10);
            контекст.closePath();
            контекст.fill();
        } else {
            // Для танка рисуем маленький кружок команды сверху
            контекст.fillStyle = цветКоманды;
            контекст.beginPath();
            контекст.arc(0, -R * 0.8, 4, 0, Math.PI * 2);
            контекст.fill();
            контекст.strokeStyle = '#000';
            контекст.lineWidth = 1 / камера.зум;
            контекст.stroke();
        }

        // Восстанавливаем трансформацию для UI (подписи, HP-бар)
        контекст.restore();
        контекст.save();
        контекст.translate(x, y);

        // Подпись
        if (камера.зум > 0.8) {
            контекст.fillStyle = '#d0d8c8';
            контекст.font = `9px 'Courier New', monospace`;
            контекст.textAlign = 'center';
            контекст.textBaseline = 'middle';
            контекст.fillText(this.метка, 0, 0);
        }

        // Полоска здоровья
        const hTriangle = this.техника ? R * 0.8 : R * 1.4;
        const шП = R * (this.техника ? 3 : 2.4), вП = 6, yП = -hTriangle/2 - 20;
        const здоровых = this.здоровье - this.раненых;
        const доляЗдоровья = this.техника ? this.здоровье / this.максЗдоровье : здоровых / this.максЗдоровье;

        контекст.fillStyle = '#080808';
        контекст.fillRect(-шП/2, yП, шП, вП);
        
        if (this.техника) {
            контекст.fillStyle = доляЗдоровья > 0.5 ? '#4caf50' : (доляЗдоровья > 0.25 ? '#ff9800' : '#f44336');
            контекст.fillRect(-шП/2, yП, шП * доляЗдоровья, вП);
        } else {
            const доляРаненых = this.раненых / this.максЗдоровье;
            контекст.fillStyle = '#6a1a1a';
            контекст.fillRect(-шП/2, yП, шП * (this.здоровье / this.максЗдоровье), вП);
            контекст.fillStyle = '#b08030';
            контекст.fillRect(-шП/2, yП, шП * доляРаненых, вП);
            контекст.fillStyle = '#3a8a3a';
            контекст.fillRect(-шП/2 + шП * доляРаненых, yП, шП * (здоровых / this.максЗдоровье), вП);
        }

        контекст.strokeStyle = '#000';
        контекст.lineWidth = 1 / камера.зум;
        контекст.strokeRect(-шП/2, yП, шП, вП);

        if (камера.зум > 0.6) {
            контекст.fillStyle = '#e8e8e0';
            контекст.font = `bold 9px 'Courier New', monospace`;
            контекст.textAlign = 'center';
            контекст.textBaseline = 'bottom';
            const текст = this.техника ? `${Math.ceil(this.здоровье * 100)}%` : (this.раненых > 0 ? `${здоровых}+${this.раненых}` : `${this.здоровье}`);
            контекст.fillText(текст, 0, yП - 2);
        }

        // Индикатор выделения
        if (this.выделен) {
            контекст.strokeStyle = '#9fdf5f';
            контекст.lineWidth = 2.5 / камера.зум;
            контекст.setLineDash([6, 4]);
            const wSel = this.техника ? R * 2.2 : R * 2;
            const hSel = this.техника ? R * 1.2 : R * 1.4;
            контекст.beginPath();
            контекст.rect(-wSel/2 - 6, -hSel/2 - 6, wSel + 12, hSel + 12);
            контекст.stroke();
            контекст.setLineDash([]);
        }

        // Индикатор атаки
        if (this.цельАтаки && this.цельАтаки.жив) {
            контекст.fillStyle = '#ff3030';
            контекст.beginPath();
            контекст.arc(шП/2 + 5, -5, 3, 0, Math.PI * 2);
            контекст.fill();
        }

        контекст.restore();
    }
}